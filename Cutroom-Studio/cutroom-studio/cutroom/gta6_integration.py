"""
Integration bridge for GTA6 Clipper repository (nocodehack.io/gta6-clipper).
Integrates GTA 6 Clipper's core engine into Cutroom Studio for Live Stream clipping:
- Uses gta6-clipper/clip.py for intelligent game/cam 9:16 reframing, animated captions & hooks.
- Uses gta6-clipper/transcribe.py and moments.py for spike and moment detection.
- Stores and serves generated Live Stream clips for the Studio page.
"""

import os, sys, json, time, shutil, subprocess, logging
from pathlib import Path
from typing import List, Dict, Optional, Any

LOG = logging.getLogger('cutroom.gta6_integration')

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1] / "gta6-clipper"
DATA_DIR = HERE.parent / "data" / "livestream_clips"
DATA_DIR.mkdir(parents=True, exist_ok=True)
INDEX_FILE = DATA_DIR / "clips_index.json"

# Ensure gta6-clipper repository is on sys.path
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

def load_index() -> List[Dict[str, Any]]:
    if not INDEX_FILE.exists():
        return []
    try:
        return json.loads(INDEX_FILE.read_text(encoding="utf-8"))
    except Exception as e:
        LOG.warning("Failed to load livestream clips index: %s", e)
        return []

def save_index(clips: List[Dict[str, Any]]):
    INDEX_FILE.write_text(json.dumps(clips, indent=2, ensure_ascii=False), encoding="utf-8")

def list_livestream_clips() -> List[Dict[str, Any]]:
    """Return all live stream clips generated by the GTA6 Clipper engine."""
    clips = load_index()
    # Filter to existing video files
    valid = []
    for c in clips:
        p = Path(c.get("filepath", ""))
        if p.is_file() and p.stat().st_size > 1000:
            valid.append(c)
    if len(valid) != len(clips):
        save_index(valid)
    return valid

def generate_clip_from_video(
    src_video: Path,
    start: float,
    end: float,
    hook: str,
    streamer: str = "Live Streamer",
    style: str = "classic",
    layout: str = "stack",
    words: Optional[List[dict]] = None
) -> Dict[str, Any]:
    """
    Generate a live-stream clip using the actual GTA6 Clipper engine (clip.py).
    Produces 1080x1920 Short with facecam on top, game below (or split),
    animated word-by-word captions, hook banner, and -14 LUFS loudness.
    """
    import clip

    clip_id = f"live_{int(time.time())}_{os.urandom(3).hex()}"
    out_mp4 = DATA_DIR / f"{clip_id}.mp4"
    out_poster = DATA_DIR / f"{clip_id}.jpg"
    tjson_path = DATA_DIR / f"{clip_id}_transcript.json"

    # Build or generate transcript formatted for gta6-clipper
    if words and len(words) > 0:
        transcript_data = {
            "lang": "en",
            "segments": [
                {
                    "start": round(start, 2),
                    "end": round(end, 2),
                    "text": " ".join((w.get("t") or w.get("w", "")) for w in words if start <= w.get("s", 0) <= end),
                    "words": [
                        {
                            "w": (w.get("t") or w.get("w", "")).strip(),
                            "s": round(float(w.get("s", 0)), 2),
                            "e": round(float(w.get("e", 0)), 2)
                        }
                        for w in words if start <= w.get("s", 0) <= end
                    ]
                }
            ]
        }
        tjson_path.write_text(json.dumps(transcript_data, ensure_ascii=False, indent=2), encoding="utf-8")
    else:
        # Run gta6-clipper's transcribe.py
        transcribe_script = REPO_ROOT / "transcribe.py"
        subprocess.run([sys.executable, str(transcribe_script), str(src_video), str(tjson_path)], check=True)

    LOG.info("Running GTA6 Clipper engine on %s (%.1fs - %.1fs) with hook '%s'...", src_video, start, end, hook)

    # Call original gta6-clipper main function directly as-is
    clip.main(
        src=str(src_video),
        tjson=str(tjson_path),
        start=str(start),
        end=str(end),
        hook=hook.upper(),
        out=str(out_mp4),
        style=style,
        layout=layout
    )

    if not out_mp4.is_file() or out_mp4.stat().st_size < 1000:
        raise RuntimeError(f"GTA6 Clipper failed to create output clip at {out_mp4}")

    # Generate thumbnail poster
    subprocess.run([
        "ffmpeg", "-y", "-loglevel", "error",
        "-ss", "1.0",
        "-i", str(out_mp4),
        "-vframes", "1",
        "-q:v", "2",
        str(out_poster)
    ], check=False)

    duration = max(0.5, end - start)
    clip_info = {
        "id": clip_id,
        "title": hook,
        "streamer": streamer,
        "duration": round(duration, 1),
        "video_url": f"/api/livestream/video/{clip_id}.mp4",
        "poster": f"/api/livestream/poster/{clip_id}.jpg" if out_poster.is_file() else "",
        "filepath": str(out_mp4),
        "created_at": time.time(),
        "engine": "gta6-clipper"
    }

    clips = load_index()
    clips.insert(0, clip_info)
    save_index(clips)

    LOG.info("GTA6 Clipper successfully produced livestream clip: %s", clip_info)
    return clip_info
